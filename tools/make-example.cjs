#!/usr/bin/env node
/* Turns a Mabat project, vocabulary or ontology file into an in-app "example" (examples/<id>.js).
   No dependencies. Usage:
     node tools/make-example.cjs <file> <id> "<Hebrew title>" "<English title>" [options]
   <file>: a Mabat project (.json / .mabat.zip), a Mabat vocabulary (.json), or a vocabulary/ontology
           source (.csv .ttl .rdf .owl .jsonld). Options:
     --desc-he "..." --desc-en "..."   short descriptions shown in the Examples window
     --source "https://..."             where the material comes from
     --license "CC BY 4.0"              license of the material (be sure you may redistribute it)
     --credit "Author, institution"    credit line shown with the example
     --group comics-holocaust           group id from examples/groups.js (optional)
   After creating the file, add <script src="examples/<id>.js"></script> to index.html before app.js. */
const fs=require('fs'),path=require('path');
const [,, file, id, titleHe, titleEn, ...rest]=process.argv;
if(!file||!id||!titleHe||!titleEn){console.error(fs.readFileSync(__filename,'utf8').split('*/')[0]);process.exit(1);}
if(!/^[a-z0-9][a-z0-9-]*$/.test(id)){console.error('id must be lowercase letters, digits and hyphens');process.exit(1);}
const opt={};for(let i=0;i<rest.length;i+=2)opt[rest[i].replace(/^--/,'')]=rest[i+1]||'';
(async()=>{
  const ext=path.extname(file).toLowerCase(),ex={id,title:{he:titleHe,en:titleEn},description:{he:opt['desc-he']||'',en:opt['desc-en']||''},source:opt.source||'',license:opt.license||'',credit:opt.credit||'',group:opt.group||''};
  if(ext==='.zip'){
    const JSZip=require(path.join(__dirname,'..','vendor','jszip.min.js'));
    const z=await JSZip.loadAsync(fs.readFileSync(file)),pj=z.file('project.json');
    if(!pj)throw Error('project.json missing: not a Mabat project ZIP');
    const project=JSON.parse(await pj.async('string')),assets={};
    for(const im of project.images){const f=z.file(im.assetPath);if(!f)throw Error('missing image '+im.assetPath);const e=im.assetPath.split('.').pop();assets[im.id]='data:'+({jpg:'image/jpeg',svg:'image/svg+xml'}[e]||'image/'+e)+';base64,'+await f.async('base64');delete im.assetPath;}
    ex.kind='project';ex.data={project,assets};
  }else if(ext==='.json'){
    const j=JSON.parse(fs.readFileSync(file,'utf8').replace(/^\uFEFF/,''));
    if(j.project||j.format==='mabat-project'){ex.kind='project';ex.data=j.project?j:{project:j,assets:{}};}
    else{ex.kind='vocabulary';ex.file=path.basename(file);ex.text=JSON.stringify(j);}
  }else if(['.csv','.ttl','.rdf','.owl','.jsonld','.xml','.nt','.n3'].includes(ext)){
    ex.kind='vocabulary';ex.file=path.basename(file);ex.text=fs.readFileSync(file,'utf8').replace(/^\uFEFF/,'');
  }else throw Error('Unsupported file type: '+ext);
  const out=path.join(__dirname,'..','examples',id+'.js');
  fs.writeFileSync(out,'/* generated by tools/make-example.cjs */\n(window.MabatExamples=window.MabatExamples||[]).push('+JSON.stringify(ex).replace(/<\/script/gi,'<\\/script')+');\n');
  console.log('Wrote',out,'(',ex.kind,')\nNow add  <script src="examples/'+id+'.js"></script>  to index.html before app.js');
})().catch(e=>{console.error('Error:',e.message);process.exit(1);});
